// "\" completion: the commands LaTeX and common packages provide, by the mode they work in, and the names
// \usepackage, \documentclass and \bibliographystyle take. Each name was checked against the TeX Live 2026
// sources: defined by its pkg, with the kernel or amsmath credited where both define it.

export type Cmd = {
  /** without the backslash, e.g. 'frac' */
  name: string;
  /** the required arguments as a run of {} (and [] where an optional one is nearly always given), e.g. '{}{}' */
  args?: string;
  /** only when args can't say it: a CodeMirror snippet() template with ${} fields, e.g. '\\left( ${} \\right)' */
  snippet?: string;
  mode: 'math' | 'text' | 'both';
  /** '' for the kernel and the standard classes, else the package or class that defines it (the one users load) */
  pkg: string;
  /** a Unicode preview of a fixed symbol, or of an accent on an "a" */
  glyph?: string;
  /** the everyday ones a typical paper uses: ranked higher */
  common?: boolean;
  /** \label, \nonumber, \notag in maths: only offered in a numbered display */
  numbered?: boolean;
  /** \tag: only offered in a display, numbered or not */
  display?: boolean;
  /** other packages or classes that define it the same way, so it's offered when one of them is loaded */
  also?: string[];
  /** only works (or only makes sense) before \begin{document} */
  preamble?: boolean;
};

